func TestRuleAptListUpgradable(t *testing.T) {
	resetTestState(t)
	rule := Get("apt_list_upgradable")
	if rule == nil {
		t.Fatal("apt_list_upgradable rule is not registered")
	}

	for _, output := range []string{
		aptListUpgradableFullEnglishOutput,
		aptListUpgradableGermanOutput,
	} {
		assertMatch(t, rule, "sudo apt update", output)
		assertNewCommands(t, rule, "sudo apt update", output,
			[]string{"sudo apt list --upgradable"})
		assertNewCommands(t, rule, "apt update", output,
			[]string{"apt list --upgradable"})
	}

	assertNotMatch(t, rule, "apt-cache search foo", "")
	assertNotMatch(t, rule, "aptitude search foo", "")
	assertNotMatch(t, rule, "apt search foo", "")
	assertNotMatch(t, rule, "apt-get install foo", "")
	assertNotMatch(t, rule, "apt-get source foo", "")
	assertNotMatch(t, rule, "apt-get clean", "")
	assertNotMatch(t, rule, "apt-get remove", "")
	assertNotMatch(t, rule, "apt-get update", "")
	assertNotMatch(t, rule, "sudo apt update", aptListUpgradableNoMatchOutput)
}
